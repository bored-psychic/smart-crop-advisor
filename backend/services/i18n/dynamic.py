def tr_crop(crop: str, lang: str) -> str:
    """Translate a crop name. Accepts either the lowercase ML class label or
    Title Case input — returns localized name, falling back to original on miss."""
    key = (crop or '').strip().lower().replace(' ', '')
    return _pick(CROP_NAME.get(key), lang, crop)


