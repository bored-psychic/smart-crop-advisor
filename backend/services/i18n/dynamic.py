"""Dynamic-string translation tables.

The static i18n catalog (`catalog.t`) handles UI chrome strings via JSON
bundles. This module localizes *backend response payloads* — crop names,
crop tips, soil-type labels, soil advice, deficiency / severity codes, and
the most common amendment notes — that flow through routers like
`/api/crop/recommend` and `/api/soil/analyze`.

One Python module instead of touching 10 large JSON bundles: keeps the
translations co-located with the data they describe, makes round-trip
lookup O(1), and avoids bundle churn during demo iteration.
"""

from typing import Optional

LANGS = ('en', 'hi', 'te', 'ta', 'kn', 'mr', 'bn', 'ml', 'gu', 'pa')
_LANG_INDEX = {code: i for i, code in enumerate(LANGS)}


def _pick(row: Optional[tuple], lang: str, fallback: str) -> str:
    """Pick row[lang_index]; fall back to English, then to the supplied fallback."""
    if not row:
        return fallback
    idx = _LANG_INDEX.get(lang, 0)
    if idx < len(row) and row[idx]:
        return row[idx]
    if row[0]:
        return row[0]
    return fallback


