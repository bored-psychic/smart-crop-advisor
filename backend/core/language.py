_FALLBACK_SESSION_STATE: dict = {}


def _session_state():
    """
    Return Streamlit session state when available.
    Falls back to a process-local dict so this module can be imported
    in backend/non-Streamlit contexts without import errors.
    """
    try:
        from importlib import import_module
        st = import_module("streamlit")
        return st.session_state
    except Exception:
        return _FALLBACK_SESSION_STATE

